local co = coroutine.create(function() error("dies") end)
print(coroutine.resume(co))
print(coroutine.status(co))
print(coroutine.close(co))
local wrapped = coroutine.wrap(function() error("wrapped error") end)
print(pcall(wrapped))
local wrapped_table = coroutine.wrap(function() error({}) end)
print(select('#', pcall(wrapped_table)))
local dead = coroutine.wrap(function() end)
dead()
print(pcall(dead))
local suspended = coroutine.create(function() coroutine.yield() end)
coroutine.resume(suspended)
print(coroutine.close(suspended), coroutine.status(suspended))
print(pcall(coroutine.close, coroutine.running()))
local closing = coroutine.create(function()
  local v <close> = setmetatable({}, {__close = function(_, e) print("closed with", e) end})
  coroutine.yield(1)
end)
print(coroutine.resume(closing))
print(coroutine.close(closing))
local failing = coroutine.create(function()
  local v <close> = setmetatable({}, {__close = function() error("close failed", 0) end})
  coroutine.yield(1)
end)
coroutine.resume(failing)
print(coroutine.close(failing))
print(coroutine.status(failing))
local nested = coroutine.wrap(function()
  local inner = coroutine.wrap(function() error("deep") end)
  inner()
end)
print(pcall(nested))
