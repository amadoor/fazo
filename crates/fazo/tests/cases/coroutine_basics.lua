local co = coroutine.create(function(a, b)
  print("start", a, b)
  local c = coroutine.yield(a + b)
  print("got", c)
  local d, e = coroutine.yield(c * 2)
  return d + e
end)
print(coroutine.status(co))
print(coroutine.resume(co, 1, 2))
print(coroutine.status(co))
print(coroutine.resume(co, 10))
print(coroutine.resume(co, 3, 4))
print(coroutine.status(co))
print(coroutine.resume(co))
print(coroutine.isyieldable())
print(select(2, coroutine.running()))
local inner = coroutine.create(function()
  print("inside", coroutine.isyieldable(), select(2, coroutine.running()))
end)
coroutine.resume(inner)
local w = coroutine.wrap(function() for i = 1, 3 do coroutine.yield(i) end return "done" end)
print(w(), w(), w(), w())
print(pcall(w))
print(pcall(coroutine.yield, 1))
print(coroutine.resume(coroutine.running()))
local self_ref
self_ref = coroutine.create(function() return coroutine.resume(self_ref) end)
print(coroutine.resume(self_ref))
print(pcall(coroutine.create, 1))
print(pcall(coroutine.resume, 1))
print(pcall(coroutine.status))
