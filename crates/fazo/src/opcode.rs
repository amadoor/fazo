use crate::instruction::Instruction;

/// Discriminants are the opcode numbers of `lopcodes.h`.
macro_rules! opcodes {
    ($($variant:ident = $name:literal,)*) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
        #[repr(u8)]
        pub(crate) enum Opcode {
            $($variant,)*
        }

        impl Opcode {
            pub(crate) const ALL: &'static [Opcode] = &[$(Opcode::$variant,)*];

            pub(crate) fn name(self) -> &'static str {
                match self {
                    $(Opcode::$variant => $name,)*
                }
            }
        }
    };
}

